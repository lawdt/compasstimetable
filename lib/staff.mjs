// Имена преподавателей приложение выводит из самой таблицы (см. learnStaff
// в sheet.mjs), поэтому новый человек подхватывается сам.
//
// Здесь — только подстраховка: сокращения, которые встречаются в единственной
// клетке и по структуре не вычисляются. Список можно оставить пустым, тогда
// такое имя просто останется частью названия урока.
const EXTRA_STAFF = [
  'Алла Г.',
  'Mrs. Strock',
  'Mrs. Str.',
  'Mrs.Str.',
];

// Наталья ведёт вторую группу английского — в таблице её помечают буквой N.
const SECOND_ENGLISH = /(^|[^a-zа-яё])N(\.|\b)/i;

// Татьяна В. ведёт местную программу. Это нужно там, где предмет назван один
// раз, а преподавателей двое: "Математика Над. / Т.В." — деление по
// программам, а не второй педагог на уроке.
const UA_TEACHER = /^(т\.\s?в\.?|татьяна\s+в\.?)$/i;

export { EXTRA_STAFF, SECOND_ENGLISH, UA_TEACHER };
